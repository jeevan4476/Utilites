// lanbeam web build script.
//
// Bundles web/app.ts and web/styles.css into a single self-contained HTML
// string and writes it to src/web_assets.rs so the Rust binary can embed the
// complete frontend via include_str!.
//
// Run with: bun run build.ts   (from the web/ directory)

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const WEB_DIR = new URL(".", import.meta.url).pathname;
const SRC_DIR = join(WEB_DIR, "..", "src");

async function main() {
  // Read sources.
  const [indexHtml, appTs, stylesCss] = await Promise.all([
    readFile(join(WEB_DIR, "index.html"), "utf8"),
    readFile(join(WEB_DIR, "app.ts"), "utf8"),
    readFile(join(WEB_DIR, "styles.css"), "utf8"),
  ]);

  // Transpile TypeScript to JavaScript. Bun.build strips type annotations and
  // `import type` statements (which browsers cannot understand). `export`
  // keywords are retained (valid ES module syntax) but unused since nothing
  // imports from this bundled module.
  const appTsPath = join(WEB_DIR, "app.ts");
  const build = await Bun.build({
    entrypoints: [appTsPath],
    bundling: "none",
    minify: false,
    target: "browser",
  });
  if (!build.success) {
    throw new Error(
      `TypeScript transpile failed: ${build.logs.map((l) => l.message).join("\n")}`
    );
  }
  const outputKey = Object.keys(build.outputs)[0];
  const output = build.outputs[outputKey];
  if (!output) {
    throw new Error("No output produced by Bun.build");
  }
  const appJs = await output.text();

  // Inline the CSS into a <style> tag, replacing the external stylesheet link.
  let bundled = indexHtml.replace(
    /<link rel="stylesheet" href="styles\.css" \/>/,
    `<style>\n${stylesCss}\n</style>`
  );

  // Replace the external module script + inline init block with one bundled
  // <script> containing the app code followed by the initialization logic.
  // Extract the init logic from the existing inline <script type="module">.
  const initMatch = bundled.match(
    /<script type="module">([\s\S]*?)<\/script>/
  );
  if (!initMatch) {
    throw new Error(
      'No <script type="module"> block found in index.html'
    );
  }
  let initJs = initMatch[1];
  // Remove the import line since app.ts is now inlined above.
  initJs = initJs.replace(
    /import\s*\{\s*LanbeamUI\s*\}\s*from\s*["']\.\/app\.ts["']\s*;?\n?/,
    ""
  );

  const bundledScript = `<script type="module">\n${appJs.trim()}\n\n// --- initialization ---\n${initJs.trim()}\n</script>`;

  // Replace the original inline script block with the bundled one.
  bundled = bundled.replace(
    /<script type="module">[\s\S]*?<\/script>/,
    bundledScript
  );

  // Rust raw string r##"..."## can contain double quotes and even "# freely;
  // we just need to ensure the closing delimiter "## does not appear.
  let rustRaw = bundled;
  if (rustRaw.includes('"##')) {
    throw new Error(
      "Bundled HTML contains '\"##' which would break the Rust raw string delimiter"
    );
  }

  const rustFile = `//! Embedded lanbeam mobile web frontend.
//!
//! This file is generated by web/build.ts. Do not edit by hand; instead
//! edit web/index.html, web/app.ts, or web/styles.css and re-run:
//!     bun run build.ts
//! (from the web/ directory).

pub const WEB_ASSETS: &str = r##"${rustRaw}"##;
`;

  await writeFile(join(SRC_DIR, "web_assets.rs"), rustFile);
  console.log("✅  Wrote src/web_assets.rs");
}

main().catch((err) => {
  console.error("build failed:", err);
  process.exit(1);
});
